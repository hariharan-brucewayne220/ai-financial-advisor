"""Report model for generated financial reports."""

from datetime import datetime
from uuid import uuid4
from typing import Optional

from sqlalchemy import Column, String, DateTime, Text, Index, ForeignKey, text
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import relationship

from app.models.base import Base


class Report(Base):
    """
    Report model for generated financial analysis reports.

    Reports are generated by the ReportWriterAgent which uses LangGraph
    to orchestrate: gather -> analyze -> draft -> self_review -> finalize.
    """

    __tablename__ = "reports"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid4)
    client_id = Column(UUID(as_uuid=True), ForeignKey("clients.id", ondelete="CASCADE"), nullable=False)
    report_type = Column(String(100), nullable=False)  # portfolio_summary, risk_assessment, client_email
    title = Column(String(255))
    content = Column(Text)  # Markdown content
    content_html = Column(Text)  # Rendered HTML
    status = Column(String(50), default="draft", index=True, nullable=False)  # draft, final, archived
    generation_metadata = Column(JSONB, default={})  # agent steps, iteration count, etc.
    created_at = Column(DateTime(timezone=True), default=datetime.utcnow, nullable=False, index=True)
    updated_at = Column(DateTime(timezone=True), default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)
    finalized_at = Column(DateTime(timezone=True))

    # Relationships
    client = relationship("Client", back_populates="reports")

    # Indexes
    __table_args__ = (
        Index("idx_reports_client_id", "client_id"),
        Index("idx_reports_status", "status"),
        Index("idx_reports_created_at", text("created_at DESC")),
    )

    def __repr__(self) -> str:
        return f"<Report(id={self.id}, type={self.report_type}, status={self.status})>"
